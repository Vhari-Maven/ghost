/**
 * Generates src/lib/assets/circuit-pattern.svg from src/lib/circuit/tile.ts so the
 * background art and the pulse-walk graph never drift apart.
 *
 *   bun run gen:circuit
 */
import { TILE_SIZE, TRACES, BRIDGES, buildGraph, isPort, validateTiling } from './tile';

const graph = buildGraph();
const problems = validateTiling(graph);
if (problems.length) {
  console.error('Tile does not tile seamlessly:\n  ' + problems.join('\n  '));
  process.exit(1);
}

const STROKE = '#1a2a2d';

const paths = TRACES.map(
  (t) => `    <path d="${t.map(([x, y], i) => `${i === 0 ? 'M' : 'L'}${x} ${y}`).join(' ')}"/>`
).join('\n');

const bridges = BRIDGES.map(
  ([[x1, y1], [x2, y2]]) => `    <path d="M${x1} ${y1} L${x2} ${y2}"/>`
).join('\n');

// Vias at dead ends, junctions and bridge ends (never at tile ports, which are just continuations)
const bridgeEnds = new Set(BRIDGES.flatMap(([a, b]) => [`${a[0]},${a[1]}`, `${b[0]},${b[1]}`]));
const vias = [...graph.nodes.values()]
  .filter((n) => !isPort(n) && (n.neighbors.length !== 2 || bridgeEnds.has(n.key)))
  .map((n) => `    <circle cx="${n.x}" cy="${n.y}" r="${n.neighbors.length >= 3 ? 1.5 : 1.2}"/>`)
  .join('\n');

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${TILE_SIZE}" height="${TILE_SIZE}" viewBox="0 0 ${TILE_SIZE} ${TILE_SIZE}">
  <!-- Generated by src/lib/circuit/generate-svg.ts from src/lib/circuit/tile.ts — do not edit by hand -->
  <g fill="none" stroke="${STROKE}" stroke-width="0.5" stroke-linecap="round" stroke-linejoin="round" opacity="0.4">
${paths}
  </g>
  <!-- Layer hops under the bundle: via, faint dashed run on the back layer, via -->
  <g fill="none" stroke="${STROKE}" stroke-width="0.5" stroke-dasharray="2 2" opacity="0.25">
${bridges}
  </g>
  <g fill="${STROKE}" opacity="0.3">
${vias}
  </g>
</svg>
`;

await Bun.write(new URL('../assets/circuit-pattern.svg', import.meta.url), svg);
console.log(`Wrote src/lib/assets/circuit-pattern.svg (${graph.nodes.size} nodes, ${TRACES.length} traces)`);
